"""Текст справки по языку формул.

Перечень функций и операторов не дублируется вручную, а собирается из
таблиц :mod:`dp_graph.expression`. Добавленная в таблицу функция появляется
в справке сама — расходиться описанию и реализации негде.
"""

from __future__ import annotations

from .expression import BINARY_OPS, CONSTANTS, FUNCTIONS

__all__ = ["build_help", "INTRO"]

INTRO = """\
[b]Как устроена формула[/b]

Формула — это выражение относительно переменной [b]x[/b]. Приложение строит график y = f(x): для каждой точки экрана подставляется своё значение x.

    x^2 - 3            парабола со сдвигом
    sin(x)/x           затухающие колебания
    sqrt(abs(x))       корень из модуля

[b]Числа[/b]

Целые и дробные пишутся привычно: [b]12[/b], [b]3.14[/b], [b].5[/b]. Очень большие и малые — через степень десяти: [b]1.6e-19[/b], [b]3e8[/b].

[b]Скобки и порядок действий[/b]

Порядок обычный: сначала степень, затем умножение и деление, затем сложение и вычитание. Скобки его меняют.

Степень правоассоциативна, как в математике: [b]2^3^2[/b] это 2^(3^2) = 512, а не (2^3)^2.

Унарный минус слабее степени, поэтому [b]-x^2[/b] это -(x^2). Если нужен квадрат отрицательного числа, поставьте скобки: [b](-x)^2[/b].

[b]Умножение можно не писать[/b]

Там, где это не создаёт двусмысленности, знак умножения необязателен:

    2x            то же, что 2*x
    3sin(x)       то же, что 3*sin(x)
    2(x+1)        то же, что 2*(x+1)

Исключение — два числа подряд: [b]2 3[/b] считается ошибкой, потому что без пробела это было бы число 23. Пишите [b]2*3[/b].

[b]Факториал[/b]

Постфиксный знак [b]![/b] считается через гамма-функцию, поэтому определён и для дробных аргументов: [b]3![/b] = 6, а [b]2.5![/b] = 3.32...

[b]Условия[/b]

Сравнения дают 1, если верно, и 0, если нет. Вместе с [b]if[/b] это даёт кусочно заданные функции:

    if(x > 0, x^2, -x)      парабола справа, прямая слева
    (x > 0) * sin(x)        синус, обрезанный нулём слева

Ветви [b]if[/b] вычисляются лениво: [b]if(x > 0, ln(x), 0)[/b] не даёт разрыва на отрицательных x, потому что ln там просто не считается.

[b]Где график прерывается[/b]

Точки вне области определения — деление на ноль, [b]ln[/b] неположительного, [b]sqrt[/b] отрицательного, [b]asin[/b] вне [-1, 1] — не ошибка. График в них просто разрывается. Вертикальные асимптоты тоже показываются разрывом, а не отвесной чертой через весь экран.

[b]Управление графиком[/b]

Один палец тянет оси, два пальца сводят и разводят масштаб. Кнопка «Сброс» возвращает исходные положение и масштаб, «‹ Меню» — к списку формул. Масштаб по обеим осям одинаковый, поэтому наклон линии на экране соответствует её настоящему коэффициенту.

[b]Регистр не важен[/b]

[b]SIN(X)[/b], [b]Sin(x)[/b] и [b]sin(x)[/b] — одно и то же.
"""


def build_help() -> str:
    """Собирает полный текст справки, включая перечень функций и операторов."""
    parts = [INTRO, _constants_section(), _operators_section(), _functions_section()]
    return "\n".join(parts)


def _constants_section() -> str:
    lines = ["", "[b]Константы[/b]", ""]
    descriptions = {
        "pi": "число пи, 3.14159...",
        "e": "основание натурального логарифма, 2.71828...",
        "tau": "два пи, полный оборот в радианах",
        "phi": "золотое сечение, 1.61803...",
    }
    for name in CONSTANTS:
        lines.append(f"    [b]{name}[/b] — {descriptions.get(name, '')}")
    lines.append("    [b]x[/b] — переменная, по которой строится график")
    return "\n".join(lines)


def _operators_section() -> str:
    lines = ["", "[b]Операторы[/b]", ""]
    # По убыванию приоритета, чтобы порядок действий читался сверху вниз.
    for op in sorted(BINARY_OPS.values(), key=lambda o: (-o.precedence, o.symbol)):
        lines.append(f"    [b]a {_escape(op.symbol)} b[/b] — {op.help}")
    lines.append("    [b]a![/b] — факториал (гамма-функция)")
    lines.append("    [b]-a[/b] — смена знака")
    return "\n".join(lines)


def _functions_section() -> str:
    groups: list[tuple[str, tuple[str, ...]]] = [
        ("Тригонометрия", ("sin", "cos", "tan", "cot", "sec", "csc")),
        ("Обратная тригонометрия", ("asin", "acos", "atan", "acot", "atan2")),
        ("Гиперболические", ("sinh", "cosh", "tanh", "asinh", "acosh", "atanh")),
        ("Степени, корни, логарифмы", ("sqrt", "cbrt", "root", "exp", "ln", "lg", "log2", "log")),
        ("Округление и знак", ("abs", "sign", "floor", "ceil", "round", "trunc", "frac")),
        ("Выбор значений", ("min", "max", "clamp", "hypot", "mod", "if")),
        ("Прочее", ("gamma", "deg", "rad")),
    ]
    lines = ["", "[b]Функции[/b]"]
    listed: set[str] = set()
    for title, names in groups:
        lines.append("")
        lines.append(f"[b]{title}[/b]")
        lines.append("")
        for name in names:
            function = FUNCTIONS[name]
            listed.add(name)
            lines.append(f"    [b]{_escape(function.signature)}[/b] — {function.help}")

    remaining = [name for name in FUNCTIONS if name not in listed]
    if remaining:  # страховка: новая функция в таблице не потеряется в справке
        lines.extend(["", "[b]Прочие функции[/b]", ""])
        for name in remaining:
            function = FUNCTIONS[name]
            lines.append(f"    [b]{_escape(function.signature)}[/b] — {function.help}")
    return "\n".join(lines)


def _escape(text: str) -> str:
    """Экранирует разметку Kivy, чтобы '[' в тексте не съедался."""
    return text.replace("&", "&amp;").replace("[", "&bl;").replace("]", "&br;")
